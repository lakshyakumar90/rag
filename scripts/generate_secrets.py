#!/usr/bin/env python3
"""Generate a local .env with fresh secrets for the production stack.

Uses only the standard library, so it can be run before installing anything:

    python scripts/generate_secrets.py

Existing files are never overwritten unless --force is passed.
"""

import argparse
import base64
import os
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fernet_key() -> str:
    """A valid Fernet key: 32 random bytes, URL-safe base64 encoded."""
    return base64.urlsafe_b64encode(os.urandom(32)).decode("ascii")


def render() -> str:
    values = {
        "POSTGRES_USER": "rag",
        "POSTGRES_PASSWORD": secrets.token_urlsafe(24),
        "POSTGRES_DB": "rag",
        "MINIO_ROOT_USER": "minioadmin",
        "MINIO_ROOT_PASSWORD": secrets.token_urlsafe(24),
        "MINIO_BUCKET": "rag",
        "JWT_SECRET_KEY": secrets.token_urlsafe(48),
        "LLM_MASTER_KEY": fernet_key(),
        "LLM_PROVIDER": "ollama",
        "OLLAMA_EMBEDDING_MODEL": "embeddinggemma-2:440m",
        "OLLAMA_LLM_MODEL": "llama3.2:latest",
        "HTTP_PORT": "80",
        "REFRESH_COOKIE_SECURE": "false",
        "TRUST_PROXY_HEADERS": "true",
    }
    lines = [
        "# Generated by scripts/generate_secrets.py — keep this file secret.",
        "# See .env.example for the full configuration reference.",
        "",
    ]
    lines.extend(f"{key}={value}" for key, value in values.items())
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / ".env",
        help="target env file (default: repo root .env)",
    )
    parser.add_argument(
        "--force", action="store_true", help="overwrite an existing env file"
    )
    args = parser.parse_args()

    if args.output.exists() and not args.force:
        parser.error(
            f"{args.output} already exists; pass --force to regenerate "
            "(this invalidates existing JWTs and encrypted BYOK keys)"
        )
    args.output.write_text(render(), encoding="utf-8")
    try:
        display = args.output.relative_to(ROOT)
    except ValueError:
        display = args.output
    print(f"Wrote {display} with fresh POSTGRES_PASSWORD, MINIO_ROOT_PASSWORD,")
    print("JWT_SECRET_KEY and LLM_MASTER_KEY. Do not commit this file.")
    print("Next: docker compose -f docker-compose.prod.yml up -d --build")


if __name__ == "__main__":
    main()
